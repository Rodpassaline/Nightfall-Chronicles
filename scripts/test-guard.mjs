import { chromium } from "playwright";
const b = await chromium.launch({ channel: "msedge", headless: true });
const p = await b.newPage({ viewport: { width: 1280, height: 800 } });
const errs = [];
p.on("pageerror", (e) => errs.push(String(e)));
await p.goto("http://127.0.0.1:8080/", { waitUntil: "networkidle" });
await (await p.waitForSelector("button:has-text('Jogar')")).click();
const c = await p.waitForSelector("canvas");
await p.waitForTimeout(800);
await c.click();
await p.keyboard.down("KeyI"); await p.waitForTimeout(400);
await c.screenshot({ path: "screenshots/g-guard.png" });
await p.keyboard.up("KeyI"); await p.waitForTimeout(200);
await p.keyboard.down("KeyJ"); await p.waitForTimeout(90);
await c.screenshot({ path: "screenshots/g-attack.png" });
await p.keyboard.up("KeyJ"); await p.waitForTimeout(300);
await p.keyboard.down("KeyL"); await p.waitForTimeout(170);
await c.screenshot({ path: "screenshots/g-cast.png" });
await p.keyboard.up("KeyL");
console.log("errors", errs);
await b.close();
